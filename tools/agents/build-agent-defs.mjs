#!/usr/bin/env node
/**
 * build-agent-defs.mjs — single-source generator for per-platform agent/command/skill files.
 *
 * The Copilot definitions under .github/ are the source of truth for the red team roster:
 *   .github/agents/redteam-*.agent.md   — the dispatchable agent "cards"
 *   .github/prompts/*.prompt.md         — the slash commands (/recon, /assess, ...)
 *   .github/skills/<name>/               — auto-loaded domain knowledge
 *
 * From those, this tool emits the equivalent definitions for the other supported runtimes
 * so the team never drifts between platforms:
 *   Claude Code -> .claude/agents, .claude/commands, .claude/skills
 *   Cursor      -> .cursor/rules,  .cursor/commands
 *   Codex CLI   -> .codex/prompts
 *
 * Usage:
 *   node tools/agents/build-agent-defs.mjs                 # generate all platforms
 *   node tools/agents/build-agent-defs.mjs --platform claude
 *   node tools/agents/build-agent-defs.mjs --check         # CI: fail if anything is stale
 *
 * The deep methodology (agents/<domain>/system-prompt.md), checks/, tools/, controls/,
 * schemas/, knowledge/ and playbooks/ are platform-neutral and referenced by relative
 * path from the generated files — they are NOT copied.
 */

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  rmSync,
  statSync,
} from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { READONLY_BANNER } from '../../guardrails/guard.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');

const SRC = {
  agents: join(ROOT, '.github', 'agents'),
  prompts: join(ROOT, '.github', 'prompts'),
  skills: join(ROOT, '.github', 'skills'),
};

const GENERATED_NOTE =
  'This file is GENERATED by tools/agents/build-agent-defs.mjs from the Copilot ' +
  'definitions under .github/. Do not edit by hand — edit the source and re-run the generator.';

// Copilot tool name -> the equivalent platform-native tool names.
const TOOL_MAP = {
  claude: {
    read: ['Read'],
    search: ['Grep', 'Glob'],
    edit: ['Edit', 'Write'],
    execute: ['Bash'],
    todo: ['TodoWrite'],
    agent: ['Task'],
  },
};

// ---------------------------------------------------------------------------
// Frontmatter parsing (minimal — these files use single-line scalar values and a
// one-line JSON-style tools array; no nested YAML).
// ---------------------------------------------------------------------------

function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { data: {}, raw: {}, body: text };
  const data = {};
  const raw = {};
  for (const line of m[1].split(/\r?\n/)) {
    const mm = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!mm) continue;
    const key = mm[1];
    const rawVal = mm[2];
    raw[key] = rawVal;
    if (rawVal.startsWith('[')) {
      try {
        data[key] = JSON.parse(rawVal);
      } catch {
        data[key] = rawVal;
      }
    } else {
      data[key] = rawVal.replace(/^["']|["']$/g, '');
    }
  }
  return { data, raw, body: m[2] };
}

// ---------------------------------------------------------------------------
// Load sources
// ---------------------------------------------------------------------------

function loadAgents() {
  return readdirSync(SRC.agents)
    .filter((f) => f.endsWith('.agent.md'))
    .sort()
    .map((f) => {
      const slug = f.replace(/\.agent\.md$/, '');
      const { data, raw, body } = parseFrontmatter(readFileSync(join(SRC.agents, f), 'utf8'));
      return { slug, file: f, data, raw, body };
    });
}

function loadPrompts() {
  return readdirSync(SRC.prompts)
    .filter((f) => f.endsWith('.prompt.md'))
    .sort()
    .map((f) => {
      const slug = f.replace(/\.prompt\.md$/, '');
      const { data, raw, body } = parseFrontmatter(readFileSync(join(SRC.prompts, f), 'utf8'));
      return { slug, file: f, data, raw, body };
    });
}

function loadSkillDirs() {
  return readdirSync(SRC.skills, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
}

// Map each agent's display name (frontmatter `name`) to its slug, so generated bodies
// can dispatch sub-agents by the platform-native identifier instead of the prose name.
function buildNameMap(agents) {
  const pairs = agents
    .map((a) => [a.data.name, a.slug])
    .filter(([name]) => typeof name === 'string' && name.length > 0)
    // Replace longer names first so "Red Team Identity" doesn't partially clobber a
    // superstring match elsewhere.
    .sort((a, b) => b[0].length - a[0].length);
  return pairs;
}

function applyNameMap(body, nameMap) {
  let out = body;
  for (const [name, slug] of nameMap) {
    out = out.split('`' + name + '`').join('`' + slug + '`');
  }
  return out;
}

// Apply both body rewrites every generated agent/command body needs: re-home skill path
// references to the platform's skill location, and swap sub-agent display names for slugs.
function rewriteBody(body, nameMap, skillTarget) {
  let out = body.replace(/\.github\/skills\//g, skillTarget);
  out = applyNameMap(out, nameMap);
  return out;
}

// ---------------------------------------------------------------------------
// Generic emit/collect: every generator returns { path, content } records and (for
// skills) { copyDir } records, so --check can compare without writing.
// ---------------------------------------------------------------------------

function mapTools(tools, platform) {
  if (!Array.isArray(tools)) return [];
  const table = TOOL_MAP[platform];
  const out = [];
  for (const t of tools) {
    for (const mapped of table[t] || []) {
      if (!out.includes(mapped)) out.push(mapped);
    }
  }
  return out;
}

// ----- Claude -----

function claudeAgentFile(agent, nameMap) {
  const tools = mapTools(agent.data.tools, 'claude').join(', ');
  let body = rewriteBody(agent.body, nameMap, '.claude/skills/');
  const fm = [
    '---',
    `name: ${agent.slug}`,
    `description: ${agent.raw.description ?? agent.data.description ?? ''}`,
    `tools: ${tools}`,
    '---',
    '',
    `<!-- ${GENERATED_NOTE} Source: .github/agents/${agent.file} -->`,
    '',
  ].join('\n');
  return {
    path: join('.claude', 'agents', `${agent.slug}.md`),
    content: fm + body.replace(/^\n+/, ''),
  };
}

function claudeCommandFile(prompt, nameMap) {
  let body = rewriteBody(prompt.body, nameMap, '.claude/skills/');
  const fm = [
    '---',
    `description: ${prompt.raw.description ?? prompt.data.description ?? ''}`,
    '---',
    '',
    `<!-- ${GENERATED_NOTE} Source: .github/prompts/${prompt.file} -->`,
    '',
  ].join('\n');
  return {
    path: join('.claude', 'commands', `${prompt.slug}.md`),
    content: fm + body.replace(/^\n+/, ''),
  };
}

// Skills are copied verbatim (platform-neutral). Returns copyDir records so --check can
// compare the trees file by file.
function claudeSkillDirs(skillDirs) {
  return skillDirs.map((name) => ({
    fromDir: join(SRC.skills, name),
    toDir: join('.claude', 'skills', name),
  }));
}

// ---------------------------------------------------------------------------
// Platform drivers
// ---------------------------------------------------------------------------

function generateClaude(agents, prompts, skillDirs, nameMap) {
  const files = [];
  for (const a of agents) files.push(claudeAgentFile(a, nameMap));
  for (const p of prompts) files.push(claudeCommandFile(p, nameMap));
  const dirs = claudeSkillDirs(skillDirs);
  return { files, dirs, roots: ['.claude/agents', '.claude/commands', '.claude/skills'] };
}

// ----- Cursor -----
//
// Cursor has no native named-subagent or skills directory, so the roster is expressed as
// rules (description-triggered context) plus slash commands, and skill knowledge is
// referenced at its canonical .github/skills/ location (read on demand). Read-only
// enforcement is handled by .cursor/hooks (not the generator).

// Escape a frontmatter scalar so a description containing ':' or quotes stays valid YAML.
function yamlScalar(value) {
  const v = String(value ?? '');
  if (v === '') return "''";
  if (/[:#"'\[\]{}|>&*!?%@`]/.test(v) || /^\s|\s$/.test(v)) {
    return '"' + v.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
  }
  return v;
}

// Always-on rule carrying the read-only posture. Generated from the single READONLY_BANNER
// source in guardrails/guard.mjs so the posture text never drifts between runtimes.
function cursorPostureRule() {
  const content = [
    '---',
    'description: Azure red team engagement — read-only posture and guardrails (always applied)',
    'alwaysApply: true',
    '---',
    '',
    `<!-- ${GENERATED_NOTE} Source: guardrails/guard.mjs (READONLY_BANNER) -->`,
    '',
    '# Azure Red Team — Read-Only Posture',
    '',
    READONLY_BANNER,
    '',
    'The `.cursor/hooks` guard enforces this allowlist on every shell command and surfaces ' +
      'MCP tool calls for approval; never attempt to bypass it. Validate engagement scope ' +
      'and operate on one subscription at a time.',
    '',
  ].join('\n');
  return { path: join('.cursor', 'rules', '00-redteam-readonly.mdc'), content };
}

function cursorAgentRule(agent, nameMap) {
  const body = rewriteBody(agent.body, nameMap, '.github/skills/');
  const fm = [
    '---',
    `description: ${yamlScalar(agent.raw.description ?? agent.data.description ?? '')}`,
    'alwaysApply: false',
    '---',
    '',
    `<!-- ${GENERATED_NOTE} Source: .github/agents/${agent.file} -->`,
    '',
  ].join('\n');
  return {
    path: join('.cursor', 'rules', `${agent.slug}.mdc`),
    content: fm + body.replace(/^\n+/, ''),
  };
}

function cursorCommandFile(prompt, nameMap) {
  const body = rewriteBody(prompt.body, nameMap, '.github/skills/');
  const head = `<!-- ${GENERATED_NOTE} Source: .github/prompts/${prompt.file} -->\n\n`;
  return {
    path: join('.cursor', 'commands', `${prompt.slug}.md`),
    content: head + body.replace(/^\n+/, ''),
  };
}

function generateCursor(agents, prompts, skillDirs, nameMap) {
  const files = [cursorPostureRule()];
  for (const a of agents) files.push(cursorAgentRule(a, nameMap));
  for (const p of prompts) files.push(cursorCommandFile(p, nameMap));
  return { files, dirs: [], roots: ['.cursor/rules', '.cursor/commands'] };
}

const PLATFORMS = {
  claude: generateClaude,
  cursor: generateCursor,
};

// ---------------------------------------------------------------------------
// Filesystem helpers
// ---------------------------------------------------------------------------

function listFilesRec(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...listFilesRec(p));
    else out.push(p);
  }
  return out;
}

function writeFileEnsured(absPath, content) {
  mkdirSync(dirname(absPath), { recursive: true });
  writeFileSync(absPath, content);
}

function copyDirInto(fromDir, toAbsDir) {
  if (existsSync(toAbsDir)) rmSync(toAbsDir, { recursive: true, force: true });
  for (const src of listFilesRec(fromDir)) {
    const rel = relative(fromDir, src);
    writeFileEnsured(join(toAbsDir, rel), readFileSync(src));
  }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function plan(platformNames) {
  const agents = loadAgents();
  const prompts = loadPrompts();
  const skillDirs = loadSkillDirs();
  const nameMap = buildNameMap(agents);
  const result = {};
  for (const name of platformNames) {
    result[name] = PLATFORMS[name](agents, prompts, skillDirs, nameMap);
  }
  return result;
}

function doGenerate(platformNames) {
  const plans = plan(platformNames);
  let count = 0;
  for (const [name, p] of Object.entries(plans)) {
    // Clear generated roots so removed sources don't leave stale files behind.
    for (const root of p.roots) {
      const abs = join(ROOT, root);
      if (existsSync(abs)) rmSync(abs, { recursive: true, force: true });
    }
    for (const f of p.files) {
      writeFileEnsured(join(ROOT, f.path), f.content);
      count++;
    }
    for (const d of p.dirs) {
      copyDirInto(d.fromDir, join(ROOT, d.toDir));
      count += listFilesRec(d.fromDir).length;
    }
    console.log(`generated ${name}: ${p.files.length} files + ${p.dirs.length} skill dirs`);
  }
  console.log(`OK — wrote ${count} files`);
}

function doCheck(platformNames) {
  const plans = plan(platformNames);
  const problems = [];
  // Compare EOL-insensitively so a CRLF working tree (git autocrlf on Windows) does not
  // read as drift against the LF the generator emits — the check is about content, not EOL.
  const norm = (buf) => buf.toString('utf8').replace(/\r\n/g, '\n');
  for (const p of Object.values(plans)) {
    for (const f of p.files) {
      const abs = join(ROOT, f.path);
      if (!existsSync(abs)) problems.push(`missing: ${f.path}`);
      else if (norm(readFileSync(abs)) !== norm(Buffer.from(f.content)))
        problems.push(`stale:   ${f.path}`);
    }
    for (const d of p.dirs) {
      for (const src of listFilesRec(d.fromDir)) {
        const rel = relative(d.fromDir, src);
        const abs = join(ROOT, d.toDir, rel);
        if (!existsSync(abs)) problems.push(`missing: ${join(d.toDir, rel)}`);
        else if (norm(readFileSync(abs)) !== norm(readFileSync(src)))
          problems.push(`stale:   ${join(d.toDir, rel)}`);
      }
    }
  }
  if (problems.length) {
    console.error('Generated platform files are out of date. Run:');
    console.error('  node tools/agents/build-agent-defs.mjs');
    console.error('Problems:');
    for (const p of problems) console.error('  ' + p);
    process.exit(1);
  }
  console.log('OK — all generated platform files are in sync with .github/ sources');
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  let platforms = Object.keys(PLATFORMS);
  const pIdx = args.indexOf('--platform');
  if (pIdx !== -1 && args[pIdx + 1]) {
    const requested = args[pIdx + 1];
    if (!PLATFORMS[requested]) {
      console.error(`Unknown platform "${requested}". Known: ${Object.keys(PLATFORMS).join(', ')}`);
      process.exit(2);
    }
    platforms = [requested];
  }
  if (check) doCheck(platforms);
  else doGenerate(platforms);
}

main();
